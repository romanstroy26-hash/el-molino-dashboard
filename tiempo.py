"""
tiempo.py -- Блок 0: единственный на всю программу ответ на вопрос
"который сейчас час и какое сегодня число".

Правило одно и без исключений: время считается по Сан-Луис-Потоси --
там, где стоят пекарни. Ни время компьютера, с которого смотрят, ни
время сервера, на котором крутится дашборд, значения не имеют.

Почему это отдельный модуль, а не константа внутри metrics.py: текущее
время нужно в разных, не связанных между собой блоках -- и в расчётах
(закрыт ли день), и в экстракторе (когда загрузили файл). Если бы
экстрактор тянул её из metrics, получилась бы зависимость "разбор файла
зависит от аналитики", которой быть не должно. А так от этого модуля
зависят все, а он -- ни от чего.

Чем это было раньше: обычным dt.datetime.now(), то есть часами той
машины, где запущена программа. Из-за этого один и тот же дашборд
отвечал по-разному в зависимости от того, откуда на него смотрят:

  - компьютер в Москве (UTC+3)      -> "сегодня" на 9 часов раньше Мехико
  - Streamlit Cloud (UTC)           -> "сегодня" на 6 часов раньше Мехико
  - телефон в Мексике               -> "сегодня" правильное

Вечером в Мексике это расходилось на целую дату: пока в пекарне ещё
суббота и магазин торгует, для облака уже наступило воскресенье -- и
дашборд показывал неполную субботу как "закрытый день", сравнивал полдня
с полным днём и рисовал падение процентов на пятьдесят, которого не было.

Про переход на летнее время думать не надо: Мексика его отменила в 2022
году, а если что-то когда-нибудь поменяется -- ZoneInfo знает про это
сама, потому что здесь указан НАЗВАНИЕ зоны, а не жёсткое смещение
"минус шесть часов".
"""

import datetime as dt
from zoneinfo import ZoneInfo

# Сан-Луис-Потоси живёт по зоне America/Mexico_City.
TZ_NEGOCIO = ZoneInfo("America/Mexico_City")


def ahora() -> dt.datetime:
    """Текущие дата и время в Сан-Луис-Потоси (с часовым поясом внутри)."""
    return dt.datetime.now(TZ_NEGOCIO)


def hoy() -> dt.date:
    """Сегодняшняя дата в Сан-Луис-Потоси.

    Именно с ней -- и только с ней -- можно сравнивать даты продаж: они
    тоже местные, их проставляет касса Wansoft в самой пекарне."""
    return ahora().date()


def sello_de_tiempo() -> str:
    """Отметка "когда это произошло" для записи в базу, тоже по местному
    времени. Без часового пояса в строке -- в базе все даты и времена
    местные, и смешивать их с UTC нельзя."""
    return ahora().replace(tzinfo=None).isoformat(timespec="seconds")


def etiqueta() -> str:
    """Короткая подпись для интерфейса: "19.09, 17:58"."""
    return ahora().strftime("%d.%m, %H:%M")
